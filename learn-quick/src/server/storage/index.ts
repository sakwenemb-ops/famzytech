import "server-only";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/** Where uploaded files live. Swap the driver for S3/Cloudflare R2 in production. */
export interface Storage {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer | null>;
  delete(key: string): Promise<void>;
}

/** Files on the server's disk, under STORAGE_DIR (default ./storage). Fine for development and a single server. */
class LocalStorage implements Storage {
  constructor(private root: string) {}

  private file(key: string) {
    // Keys are generated by us, but never let one escape the storage folder
    const p = path.resolve(this.root, key);
    if (!p.startsWith(path.resolve(this.root) + path.sep)) throw new Error("Bad storage key");
    return p;
  }

  async put(key: string, data: Buffer) {
    const p = this.file(key);
    await mkdir(path.dirname(p), { recursive: true });
    await writeFile(p, data);
  }

  async get(key: string) {
    try {
      return await readFile(this.file(key));
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw e;
    }
  }

  async delete(key: string) {
    await rm(this.file(key), { force: true });
  }
}

let instance: Storage | undefined;
export function storage(): Storage {
  if (!instance) {
    const driver = process.env.STORAGE_DRIVER ?? "local";
    if (driver !== "local") throw new Error(`Storage driver "${driver}" is not set up yet`);
    instance = new LocalStorage(process.env.STORAGE_DIR ?? path.join(process.cwd(), "storage"));
  }
  return instance;
}
